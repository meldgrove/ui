export type Row = { id: string; title: string; status: string; person: string; updated: string };

export type List = {
  key: string;
  label: string;
  icon: LucideIcon;
  description: string;
  /** Column headers; the id column only where records have a number. */
  columns: { title: string; status: string; person: string; updated: string };
  showId: boolean;
  /** What the breadcrumb shows for one record: its number (short) or its name. */
  crumb: "id" | "title";
  newLabel?: string;
  badge?: number;
  text: string;
  rows: Row[];
};

